#!/usr/bin/env python3
"""APEX Fusion Pro: every table of apex/REPORT_FUSION.md, written to results/fusion_tables.md.

Simulation rules (mgmt["closeStop"]): 0 = the script as received, 1 = v2 (a stop raised by a fill is filled on
the same bar when that bar closes through it), 2 = pessimistic bound (any touch of the raised stop counts).
Usage: python3 study_fusion.py
"""
import os

import numpy as np

import datasets as ds
import fusion_engine as F
import fusion_lib as fl
import research_lib as rl

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "results")
TF_AR = {"5m": "5 دقائق", "15m": "15 دقيقة", "1h": "ساعة", "4h": "4 ساعات", "1D": "يومي"}
ASSET_AR = {"metal": "معادن", "energy": "طاقة", "fx": "عملات", "index": "مؤشرات", "stock": "أسهم", "crypto": "كريبتو"}
PROF_AR = {"SHD": "Shield (0.05R)", "SNP": "Sniper (0.2R)", "MW": "Max Win-Rate (0.4R)", "HW": "High Win-Rate (0.5R)",
           "BAL": "Balanced Pro (1R)", "RUN": "Trend Runner (1R)"}
FINE = {"1D": ("1h", "4h"), "4h": ("1h", "15m"), "1h": ("15m", "5m"), "15m": ("5m",)}
HEAD = ("| {first} | الصفقات | نسبة النجاح | مجال الثقة 95% | بلوغ الهدف 1 | متوسط R للصفقة | معامل الربح | الصافي R | أقصى تراجع R |\n"
        "|---|---|---|---|---|---|---|---|---|")
lines = []
_FEAT = {}


def emit(s=""):
    lines.append(s)


def pct(x):
    return "—" if x != x else f"{100 * x:.1f}%"


def row(label, trades):
    a = rl.summary(trades)
    if a["n"] == 0:
        return f"| {label} | 0 | — | — | — | — | — | — | — |"
    return (f"| {label} | {a['n']} | {pct(a['win'])} | {100*a['win_lo']:.0f}–{100*a['win_hi']:.0f}% | {pct(a['tp1'])} | "
            f"{a['avgR']:+.3f} | {a['pf']:.2f} | {a['netR']:+.1f} | {a['maxDD']:.1f} |")


def run(uni, prof=None, rule=0, p=None):
    p = p or F.FParams()
    m = {"closeStop": rule}
    if prof:
        m = {**F.PROFILES[prof], "closeStop": rule}
    return fl.run_all(uni, p, m, key="default" if p == F.FParams() else None)


def fine_for(s, min_bars):
    m = s.market
    for itv in FINE.get(s.tf, ()):
        nm = f"{m.exchange}_{m.ticker}_{itv}"
        if os.path.exists(f"{ds.DATA}/{nm}.csv"):
            fb = ds.load(nm)
            di = np.searchsorted(s.chart["t"], fb["t"], side="right") - 1
            if len(np.unique(di[di >= 0])) >= min_bars:
                return nm, fb
    return None, None


def replay(uni, prof, min_bars):
    """-> {0, 1, 2: chart-bar trades under each rule, "replay": intrabar replay}, list of series used"""
    p = F.FParams()
    res = {0: [], 1: [], 2: [], "replay": []}
    used = []
    conv = lambda ts: [{"R": t["R"], "hit1": t["hit1"], "reason": t["reason"], "t": t["entry_bar"], "cost_R": t["cost_R"]} for t in ts]
    for s in uni:
        nm, fb = fine_for(s, min_bars)
        if nm is None:
            continue
        used.append(f"{s.name} ← {nm.rsplit('_', 1)[1]}")
        ctx = F.context(s.name)
        if s.name not in _FEAT:
            _FEAT[s.name] = F.features(ctx, p)
        f = _FEAT[s.name]
        for rule in (0, 1, 2):
            tf_, tc_, _, _ = F.replay(ctx, f, fb, p, {**F.PROFILES[prof], "closeStop": rule})
            res[rule] += conv(tc_)
            if rule == 1:
                res["replay"] += conv(tf_)
    return res, used


def main():
    os.makedirs(OUT, exist_ok=True)
    allu = fl.series(roles=("primary", "replica"))
    prim = [s for s in allu if s.role == "primary"]
    gold = sorted([s for s in allu if s.underlying == "GOLD"], key=lambda s: (rl.TF_ORDER.index(s.tf), s.name))
    emit(f"<!-- generated by study_fusion.py: {len(prim)} primary series, {sum(s.n for s in prim):,} bars -->")

    tr0, info = run(prim)
    emit("\n### F1 السكربت كما استلمته (الإعدادات الافتراضية)، كل الأسواق\n")
    emit(HEAD.format(first="الفريم"))
    for tf in rl.TF_ORDER:
        emit(row(TF_AR[tf], [t for t in tr0 if t["tf"] == tf]))
    emit(f"\nالإشارات {info['signals']}، نُفّذ منها {info['filled']} (تحت الساعة الدخول بأمر محدد لا يُنفَّذ دائمًا).")

    emit("\n### F2 الذهب، الإعدادات الافتراضية (مصدران: OANDA و Yahoo/COMEX)\n")
    emit(HEAD.format(first="السلسلة (منفَّذ / إشارات)"))
    for s in gold:
        t, i = fl.run_series(s, F.FParams(), {"closeStop": 0}, key="default")
        emit(row(f"{s.name} ({i['filled']}/{i['signals']})", t))

    emit("\n### F3 الإعدادات الافتراضية حسب نوع السوق والفريم\n")
    emit(HEAD.format(first="السوق / الفريم"))
    for a in ("metal", "energy", "fx", "index", "stock", "crypto"):
        for grp, tfs in (("تحت الساعة", ("5m", "15m")), ("ساعة", ("1h",)), ("4 ساعات", ("4h",)), ("يومي", ("1D",))):
            emit(row(f"{ASSET_AR[a]} — {grp}", [t for t in tr0 if t["asset"] == a and t["tf"] in tfs]))

    emit("\n### F4 الإعدادات الافتراضية حسب النموذج والاتجاه\n")
    emit(HEAD.format(first="النموذج / الاتجاه"))
    for su in ("B&R", "ORB", "BRK", "EMA", "PB", "FLIP", "VWAP"):
        emit(row(su, [t for t in tr0 if t["trig"] == su]))
    for grp, tfs in (("تحت الساعة", ("5m", "15m")), ("ساعة", ("1h",)), ("4 ساعات + يومي", ("4h", "1D"))):
        for d, dl in ((1, "شراء"), (-1, "بيع")):
            emit(row(f"{grp} — {dl}", [t for t in tr0 if t["tf"] in tfs and t["dir"] == d]))

    groups = (("الذهب تحت الساعة (5 و15 دقيقة، 4 سلاسل)", [s for s in gold if s.tf in ("5m", "15m")]),
              ("الذهب ساعة (سلسلتان)", [s for s in gold if s.tf == "1h"]),
              ("الذهب 4 ساعات + يومي", [s for s in gold if s.tf in ("4h", "1D")]))
    emit("\n### F5 ملفات الإدارة على الذهب (القاعدة 1 = المحاكاة المصحّحة)\n")
    emit(HEAD.format(first="المجموعة / الملف"))
    for gname, uni in groups:
        for prof in ("SHD", "SNP", "MW", "HW", "BAL", "RUN"):
            emit(row(f"{gname} — {PROF_AR[prof]}", run(uni, prof, 1)[0]))

    emit("\n### F6 أثر قاعدة المحاكاة على الذهب: 0 = كما في السكربت الأصلي، 1 = المصحّحة، 2 = أسوأ افتراض\n")
    emit(HEAD.format(first="المجموعة / الملف / القاعدة"))
    for gname, uni in groups:
        for prof in ("SHD", "SNP", "MW"):
            for rule in (0, 1, 2):
                emit(row(f"{gname} — {PROF_AR[prof]} — القاعدة {rule}", run(uni, prof, rule)[0]))

    emit("\n### F7 إعادة تمثيل الصفقات على بيانات الفريم الأصغر\n")
    emit(HEAD.format(first="المجموعة / الملف / الطريقة"))
    sets = (("الذهب 15 دقيقة ← 5 دقائق", [s for s in gold if s.tf == "15m"], 800),
            ("الذهب 4 ساعات ويومي ← ساعة", [s for s in gold if s.tf in ("4h", "1D")], 150),
            ("كل الأسواق يومي ← ساعة / 4 ساعات", [s for s in prim if s.tf == "1D"], 400))
    notes = []
    for gname, uni, mb in sets:
        for prof in ("SHD", "SNP", "MW"):
            res, used = replay(uni, prof, mb)
            emit(row(f"{gname} — {PROF_AR[prof]} — شمعة الشارت، القاعدة 1", res[1]))
            emit(row(f"{gname} — {PROF_AR[prof]} — شمعة الشارت، القاعدة 2", res[2]))
            emit(row(f"**{gname} — {PROF_AR[prof]} — تمثيل داخلي**", res["replay"]))
        notes.append(f"{gname}: {len(used)} سلسلة")
    emit("\n" + "؛ ".join(notes) + ".")

    emit("\n### F8 ملفات الإدارة على كل الأسواق (القاعدة 1)\n")
    emit(HEAD.format(first="الفريم / الملف"))
    for grp, tfs in (("تحت الساعة", ("5m", "15m")), ("ساعة", ("1h",)), ("4 ساعات", ("4h",)), ("يومي", ("1D",))):
        uni = [s for s in prim if s.tf in tfs]
        for prof in ("SHD", "SNP", "MW", "HW", "RUN"):
            emit(row(f"{grp} — {PROF_AR[prof]}", run(uni, prof, 1)[0]))

    emit("\n### F9 الذهب تحت الساعة: Sniper مقابل Max Win-Rate لكل سلسلة (القاعدة 1)\n")
    emit(HEAD.format(first="السلسلة / الملف"))
    for s in gold:
        if s.tf in ("5m", "15m"):
            for prof in ("SNP", "MW"):
                emit(row(f"{s.name} — {PROF_AR[prof]}", run([s], prof, 1)[0]))

    path = os.path.join(OUT, "fusion_tables.md")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\n".join(lines))
    print("\nwritten:", path)


if __name__ == "__main__":
    main()
