#!/usr/bin/env python3
"""Regenerates every table of apex/REPORT.md from the engine (markdown, Arabic headers) into results/tables.md.

The report's numbers are copied from this output, never typed by hand.
Usage: python3 build_tables.py
"""
import os

import numpy as np

import apex_v2 as v2
import research_lib as rl

E = rl.E
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "results")
TF_AR = {"5m": "5 دقائق", "15m": "15 دقيقة", "1h": "ساعة", "4h": "4 ساعات", "1D": "يومي"}
ASSET_AR = {"metal": "معادن", "energy": "طاقة", "fx": "عملات", "index": "مؤشرات", "stock": "أسهم", "crypto": "كريبتو"}
CELL_AR = {"TRAIN": "بيانات الضبط", "TEST_TIME": "فترة لم تُستخدم", "TEST_INSTR": "أسواق لم تُستخدم"}
PURE = {"k1": 1.0, "k2": 2.0, "k3": 3.0, "w1": 1.0, "w2": 0.0, "trailOn": False, "trailFrom": 1, "beOn": False}
lines: list[str] = []


def emit(s=""):
    lines.append(s)


def run(uni, dir_mode="Auto", profile="AUTO", mgmt=None, cost_fn=None, v2_sim=True, **pkw):
    """v2_sim: use the v2 simulation rule (same-bar close through a raised stop) when the engine supports it."""
    def mg(s):
        m = dict(mgmt) if mgmt else v2.mgmt(s.market, profile)
        if v2_sim and getattr(v2, "HAS_CLOSE_STOP", False):
            m["closeStop"] = True
        return m
    return rl.run_universe(uni, params_fn=lambda s: v2.params(s.market, dir_mode, **pkw), mgmt_fn=mg, cost_fn=cost_fn)


def pct(x):
    return "—" if x != x else f"{100 * x:.1f}%"


def full_row(label, trades):
    a = rl.summary(trades)
    if a["n"] == 0:
        return f"| {label} | 0 | — | — | — | — | — | — | — |"
    return (f"| {label} | {a['n']} | {pct(a['win'])} | {100*a['win_lo']:.0f}–{100*a['win_hi']:.0f}% | {pct(a['tp1'])} | "
            f"{a['avgR']:+.3f} | {a['pf']:.2f} | {a['netR']:+.1f} | {a['maxDD']:.1f} |")


FULL_HEAD = ("| {first} | الصفقات | نسبة النجاح | مجال الثقة 95% | بلوغ الهدف 1 | متوسط R للصفقة | معامل الربح | الصافي R | أقصى تراجع R |\n"
             "|---|---|---|---|---|---|---|---|---|")


def cells_row(label, trades):
    out = f"| {label} |"
    for c in ("TRAIN", "TEST_TIME", "TEST_INSTR"):
        a = rl.summary(rl.cell(trades, c))
        out += " — | — | — | — |" if a["n"] == 0 else f" {a['n']} | {pct(a['win'])} | {a['avgR']:+.3f} | {a['pf']:.2f} |"
    return out


CELLS_HEAD = ("| {first} | ضبط: صفقات | نجاح | متوسط R | معامل الربح | فترة جديدة: صفقات | نجاح | متوسط R | معامل الربح | "
              "أسواق جديدة: صفقات | نجاح | متوسط R | معامل الربح |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|")


def main():
    os.makedirs(OUT, exist_ok=True)
    uni = rl.universe()
    by_tf = {tf: [s for s in uni if s.tf == tf] for tf in rl.TF_ORDER}
    emit(f"<!-- generated by build_tables.py: {len(uni)} primary series, {sum(s.n for s in uni):,} bars -->")
    emit("\n### T0 حجم البيانات\n")
    emit("| الفريم | عدد السلاسل | عدد الشموع | أسواق الضبط | أسواق مستبعدة للاختبار |\n|---|---|---|---|---|")
    for tf in rl.TF_ORDER:
        sub = by_tf[tf]
        emit(f"| {TF_AR[tf]} | {len(sub)} | {sum(s.n for s in sub):,} | {sum(s.group == 'tune' for s in sub)} | {sum(s.group == 'holdout' for s in sub)} |")
    emit(f"| المجموع | {len(uni)} | {sum(s.n for s in uni):,} | {sum(s.group == 'tune' for s in uni)} | {sum(s.group == 'holdout' for s in uni)} |")

    t_v1 = run(uni, dir_mode="Both", v2_sim=False)
    t_v2 = run(uni, dir_mode="Auto")
    emit("\n### T1 السكربت كما استلمته (الإعدادات الافتراضية)، كل البيانات\n")
    emit(FULL_HEAD.format(first="الفريم"))
    for tf in rl.TF_ORDER:
        emit(full_row(TF_AR[tf], [t for t in t_v1 if t["tf"] == tf]))
    emit("\nبدون الكريبتو (ملف High-Probability، هدف أول 0.3R):\n")
    emit(FULL_HEAD.format(first="الفريم"))
    for tf in rl.TF_ORDER:
        emit(full_row(TF_AR[tf], [t for t in t_v1 if t["tf"] == tf and t["asset"] != "crypto"]))

    emit("\n### T2 النسخة الأصلية مقابل النسخة المطوّرة (الإعدادات الافتراضية)، بيانات لم تُستخدم في الضبط فقط\n")
    emit(FULL_HEAD.format(first="الفريم / النسخة"))
    for tf in rl.TF_ORDER:
        emit(full_row(f"{TF_AR[tf]} — الأصلية", rl.cell([t for t in t_v1 if t["tf"] == tf], "TEST")))
        emit(full_row(f"{TF_AR[tf]} — المطوّرة", rl.cell([t for t in t_v2 if t["tf"] == tf], "TEST")))

    def frontier(tf, rows):
        sub = by_tf[tf]
        emit(CELLS_HEAD.format(first="الهدف الأول / نسبة الإغلاق"))
        for k1, w1 in rows:
            m = {"k1": k1, "k2": max(1.5, 2 * k1), "k3": max(4.0, 4 * k1), "w1": w1, "w2": 0.25 if w1 < 1 else 0.0,
                 "trailOn": True, "trailFrom": 1, "beOn": True}
            emit(cells_row(f"{k1:.2f}R / {int(100 * w1)}%", run(sub, mgmt=m)))
        emit(cells_row("Trend Runner (1R/2R/8R)", run(sub, profile="RUN")))

    emit("\n### T3 ثمن نسبة النجاح: الفريم اليومي، الاتجاه Auto\n")
    frontier("1D", ((0.05, 1.0), (0.08, 1.0), (0.10, 1.0), (0.15, 1.0), (0.20, 1.0), (0.30, 1.0), (0.15, 0.5), (0.30, 0.5), (0.50, 0.5), (1.00, 0.5)))
    emit("\n### T3b ثمن نسبة النجاح: فريم 4 ساعات، الاتجاه Auto\n")
    frontier("4h", ((0.05, 1.0), (0.10, 1.0), (0.15, 0.5), (0.30, 0.5), (1.00, 0.5)))

    emit("\n### T4 ملفات إدارة الصفقة في النسخة المطوّرة (الاتجاه Auto)\n")
    emit(CELLS_HEAD.format(first="الفريم / الملف"))
    for tf in ("1D", "4h"):
        for prof, name in (("SNP", "Sniper"), ("HP", "High-Probability"), ("BAL", "Balanced"), ("RUN", "Trend Runner")):
            emit(cells_row(f"{TF_AR[tf]} — {name}", run(by_tf[tf], profile=prof)))

    emit("\n### T5 مصدر الأفضلية: إشارات السكربت مقابل دخول عشوائي (صفقة 1R مقابل 1R، بدون تكلفة)\n")
    emit("| الفريم / الاتجاه | إشارات السكربت: صفقات | نجاح | دخول عشوائي: نجاح | عشوائي والتوافق 7/7: نجاح |\n|---|---|---|---|---|")
    feats = {s.name: E.features(s.chart, s.htf, E.Params(smallGuard=False), s.market, s.base) for s in uni}
    rng = np.random.default_rng(12345)

    def sim(s, f, ls, ss):
        c = s.chart
        rec, _, _ = E.simulate_arrays(c["o"], c["h"], c["l"], c["c"], ls, ss, f["slDistL"], f["slDistS"], f["chandL"],
                                      f["chandS"], PURE, 0.0, f["mintick"])
        return [r["R"] > 0 for r in E.trades_list(rec)]

    for grp, tfs in (("5 دقائق – ساعة", ("5m", "15m", "1h")), ("4 ساعات", ("4h",)), ("يومي", ("1D",))):
        for d, dl in ((1, "شراء"), (-1, "بيع")):
            sig, rnd, rnd7 = [], [], []
            for s in uni:
                if s.tf not in tfs:
                    continue
                f = feats[s.name]
                zero = np.zeros(s.n, bool)
                ls = f["longSig"] if d == 1 else zero
                ss = f["shortSig"] if d == -1 else zero
                sig += sim(s, f, ls, ss)
                k = int((ls | ss).sum())
                ok = np.zeros(s.n, bool)
                ok[250:] = True
                ok &= np.isfinite(f["slDistL"]) & np.isfinite(f["slDistS"])
                state = ok & ((f["scoreL"] >= 7) if d == 1 else (f["scoreS"] >= 7))
                for _ in range(6):
                    for pool, out in ((ok, rnd), (state, rnd7)):
                        idx = np.flatnonzero(pool)
                        if len(idx):
                            pick = np.zeros(s.n, bool)
                            pick[rng.choice(idx, size=min(len(idx), max(3 * k, 20)), replace=False)] = True
                            out += sim(s, f, pick if d == 1 else zero, pick if d == -1 else zero)
            emit(f"| {grp} — {dl} | {len(sig)} | {pct(np.mean(sig))} | {pct(np.mean(rnd))} | {pct(np.mean(rnd7))} |")

    emit("\n### T6 الشراء والبيع حسب نوع السوق (4 ساعات + يومي، صفقة 1R مقابل 1R، بتكلفة السكربت)\n")
    emit("| السوق / الاتجاه | ضبط: صفقات | نجاح | متوسط R | فترة جديدة: صفقات | نجاح | متوسط R | أسواق جديدة: صفقات | نجاح | متوسط R |\n|---|---|---|---|---|---|---|---|---|---|")
    tr = []
    for s in uni:
        if s.tf in ("4h", "1D"):
            t, _ = rl.run_series(s, None, PURE, None, None, feats[s.name])
            tr.extend(t)
    for a in ("metal", "energy", "fx", "index", "stock", "crypto"):
        for d, dl in ((1, "شراء"), (-1, "بيع")):
            sub = [t for t in tr if t["asset"] == a and t["dir"] == d]
            row = f"| {ASSET_AR[a]} — {dl} |"
            for c in ("TRAIN", "TEST_TIME", "TEST_INSTR"):
                x = rl.summary(rl.cell(sub, c))
                row += " — | — | — |" if x["n"] == 0 else f" {x['n']} | {pct(x['win'])} | {x['avgR']:+.3f} |"
            emit(row)

    emit("\n### T7 فريم 5 دقائق (النسخة المطوّرة، كل البيانات)\n")
    emit(FULL_HEAD.format(first="الحالة"))
    sub = by_tf["5m"]
    auto_cost = lambda s: E.cost_pct(E.Params(), s.market)
    emit(full_row("الحارس مفعّل، تكلفة السكربت", run(sub)))
    emit(full_row("الحارس معطّل، تكلفة السكربت", run(sub, smallGuard=False)))
    emit(full_row("الحارس معطّل، ثلث التكلفة", run(sub, smallGuard=False, cost_fn=lambda s: auto_cost(s) / 3)))
    t0 = run(sub, smallGuard=False, cost_fn=lambda s: 0.0)
    emit(full_row("الحارس معطّل، تكلفة صفر", t0))
    for a in ("metal", "energy", "fx", "index", "stock", "crypto"):
        emit(full_row(f"تكلفة صفر — {ASSET_AR[a]}", [t for t in t0 if t["asset"] == a]))
    emit("\nللمقارنة، 15 دقيقة وساعة:\n")
    emit(FULL_HEAD.format(first="الحالة"))
    for tf in ("15m", "1h"):
        emit(full_row(f"{TF_AR[tf]} — تكلفة السكربت", run(by_tf[tf])))
        emit(full_row(f"{TF_AR[tf]} — تكلفة صفر", run(by_tf[tf], smallGuard=False, cost_fn=lambda s: 0.0)))

    emit("\n### T8 الذهب (كل المصادر)\n")
    emit(FULL_HEAD.format(first="السلسلة / الإعداد"))
    gold = [s for s in rl.universe(roles=("primary", "replica")) if s.underlying == "GOLD"]
    for s in sorted(gold, key=lambda s: (rl.TF_ORDER.index(s.tf), s.name)):
        emit(full_row(f"{s.name} — الأصلية", run([s], dir_mode="Both", v2_sim=False)))
        for prof, name in (("SNP", "Sniper"), ("HP", "High-Probability"), ("RUN", "Trend Runner")):
            emit(full_row(f"{s.name} — المطوّرة {name}", run([s], profile=prof)))

    emit("\n### T9 النسخة المطوّرة حسب نوع السوق (4 ساعات + يومي، الإعدادات الافتراضية)\n")
    emit(CELLS_HEAD.format(first="السوق"))
    for a in ("metal", "energy", "fx", "index", "stock", "crypto"):
        emit(cells_row(ASSET_AR[a], [t for t in t_v2 if t["asset"] == a and t["tf"] in ("4h", "1D")]))

    if getattr(v2, "HAS_CLOSE_STOP", False):
        emit("\n### T10 أثر تصحيح «الإغلاق عبر الوقف المرفوع في نفس الشمعة» (الاتجاه Auto، ملف High-Probability)\n")
        emit(FULL_HEAD.format(first="الفريم / القاعدة"))
        for tf in ("4h", "1D"):
            emit(full_row(f"{TF_AR[tf]} — قاعدة النسخة الأصلية", run(by_tf[tf], profile="HP", v2_sim=False)))
            emit(full_row(f"{TF_AR[tf]} — القاعدة المصحّحة", run(by_tf[tf], profile="HP")))

    path = os.path.join(OUT, "tables.md")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(f"\nwritten: {path}")


if __name__ == "__main__":
    main()
